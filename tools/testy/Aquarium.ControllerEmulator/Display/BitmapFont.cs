  private static byte[] Glyph(params string[] rows)
  {
    if (rows.Length != 7)
    {
      throw new ArgumentException("Bitmap font glyph must contain exactly 7 rows.");
    }

    var glyph = new byte[7];
    for (var y = 0; y < rows.Length; y++)
    {
      var row = rows[y];
      if (row.Length != 5)
      {
        throw new ArgumentException("Bitmap font row must contain exactly 5 columns.");
      }

      byte mask = 0;
      for (var x = 0; x < row.Length; x++)
      {
        if (row[x] == '#')
        {
          mask |= (byte)(1 << (4 - x));
        }
      }

      glyph[y] = mask;
    }

    return glyph;
  }
