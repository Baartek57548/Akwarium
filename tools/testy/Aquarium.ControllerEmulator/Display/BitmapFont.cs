namespace Aquarium.ControllerEmulator.Display;

public sealed class BitmapFont
{
  private readonly Dictionary<char, byte[]> _glyphs = BuildGlyphs();

  public int GlyphWidth => 5;
  public int GlyphHeight => 7;
  public int CharSpacing => 1;

  public ReadOnlySpan<byte> GetGlyph(char character)
  {
    var normalized = Normalize(character);
    if (_glyphs.TryGetValue(normalized, out var glyph))
    {
      return glyph;
    }

    return _glyphs['?'];
  }

  public int MeasureTextWidth(string text)
  {
    if (string.IsNullOrEmpty(text))
    {
      return 0;
    }

    return text.Length * (GlyphWidth + CharSpacing) - CharSpacing;
  }

  private static char Normalize(char value)
  {
    return value switch
    {
      'ą' or 'Ą' => 'A',
      'ć' or 'Ć' => 'C',
      'ę' or 'Ę' => 'E',
      'ł' or 'Ł' => 'L',
      'ń' or 'Ń' => 'N',
      'ó' or 'Ó' => 'O',
      'ś' or 'Ś' => 'S',
      'ż' or 'Ż' => 'Z',
      'ź' or 'Ź' => 'Z',
      _ => char.ToUpperInvariant(value)
    };
  }

